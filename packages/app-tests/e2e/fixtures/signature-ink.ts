/** Marks a field inserted with a typed signature or text, as an earlier insert would have left it. */
export const seedInserted = async (
  seeded: G4Seeded,
  recipientKey: string,
  fieldKey: string,
  value: { typed?: string; image?: string; text?: string },
) => {
  const recipient = seeded.r[recipientKey];
  const field = recipient.fields[fieldKey];

  await prisma.field.update({
    where: { id: field.id },
    data: { inserted: true, customText: value.text ?? '' },
  });

  if (value.typed !== undefined || value.image !== undefined) {
    await prisma.signature.create({
      data: {
        fieldId: field.id,
        recipientId: recipient.id,
        typedSignature: value.typed ?? null,
        signatureImageAsBase64: value.image ?? null,
      },
    });
  }
};

