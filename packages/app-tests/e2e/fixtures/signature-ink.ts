let seedCounter = 0;

export const uniqueStamp = () => `${Date.now().toString(36)}${(seedCounter++).toString(36)}${nanoid(4).toLowerCase()}`;

/**
 * An envelope written straight through Prisma: a documentMeta with the given
 * signing order and method flags, an item carrying the example PDF, and the
 * recipients in the order given (so ids ascend in that order), each with its
 * fields laid out down page 1. PENDING envelopes get recipients SENT and
 * NOT_OPENED unless stated; signedAt is null.
 */
export const seedG4Envelope = async (options: SeedG4Options): Promise<G4Seeded> => {
  const owner = options.owner ?? (await createG4Owner());
  const stamp = uniqueStamp();
  const type = options.type ?? EnvelopeType.DOCUMENT;
  const status = options.status ?? DocumentStatus.PENDING;
  const title = options.title ?? `G4 ${stamp}`;

  const documentData = await prisma.documentData.create({
    data: { type: DocumentDataType.BYTES_64, data: EXAMPLE_PDF, initialData: EXAMPLE_PDF },
  });

  const documentMeta = await prisma.documentMeta.create({
    data: {
      signingOrder: options.signingOrder ?? DocumentSigningOrder.PARALLEL,
      allowDictateNextSigner: options.allowDictateNextSigner ?? false,
      typedSignatureEnabled: options.typedSignatureEnabled ?? true,
      drawSignatureEnabled: options.drawSignatureEnabled ?? true,
      uploadSignatureEnabled: options.uploadSignatureEnabled ?? true,
    },
  });

  const secondaryId =
    type === EnvelopeType.TEMPLATE
      ? (await incrementTemplateId()).formattedTemplateId
      : (await incrementDocumentId()).formattedDocumentId;

  const itemId = prefixedId('envelope_item');

  const envelope = await prisma.envelope.create({
    data: {
      id: prefixedId('envelope'),
      secondaryId,
      internalVersion: options.internalVersion,
      signatureLevel: options.signatureLevel ?? 'SES',
      type,
      documentMetaId: documentMeta.id,
      source: type === EnvelopeType.TEMPLATE ? DocumentSource.TEMPLATE : DocumentSource.DOCUMENT,
      teamId: owner.team.id,
      userId: owner.user.id,
      title,
      status,
      envelopeItems: { create: { id: itemId, title, documentDataId: documentData.id, order: 1 } },
    },
  });

  const r: Record<string, SeededRecipient> = {};
  let row = 0;

  for (const spec of options.recipients) {
    const mailbox = `g4-${stamp}-${spec.key}`.toLowerCase();
    const email = spec.email ?? `${mailbox}@test.documenso.com`;
    const name = spec.name ?? `G4 ${spec.key}`;
    const isPending = status === DocumentStatus.PENDING;

    const recipient = await prisma.recipient.create({
      data: {
        envelopeId: envelope.id,
        email,
        name,
        token: nanoid(),
        role: spec.role ?? 'SIGNER',
        signingOrder: spec.signingOrder,
        signingStatus: spec.signingStatus ?? SigningStatus.NOT_SIGNED,
        sendStatus: spec.sendStatus ?? (isPending ? SendStatus.SENT : SendStatus.NOT_SENT),
        readStatus: spec.readStatus ?? ReadStatus.NOT_OPENED,
        signedAt: spec.signingStatus === SigningStatus.SIGNED ? outsideSweepWindow() : null,
      },
    });

    const fields: Record<string, SeededField> = {};

    for (const field of spec.fields ?? []) {
      const created = await prisma.field.create({
        data: {
          envelopeId: envelope.id,
          envelopeItemId: itemId,
          recipientId: recipient.id,
          type: field.type,
          page: 1,
          positionX: new Prisma.Decimal(8 + (row % 3) * 30),
          positionY: new Prisma.Decimal(8 + Math.floor(row / 3) * 11),
          width: new Prisma.Decimal(24),
          height: new Prisma.Decimal(field.type === FieldType.SIGNATURE ? 8 : 5),
          customText: '',
          inserted: field.inserted ?? false,
          fieldMeta: (field.fieldMeta ?? metaFor(field.type)) as never,
        },
      });

      row++;
      fields[field.key] = { id: created.id, secondaryId: created.secondaryId, type: created.type };
    }

    r[spec.key] = { id: recipient.id, token: recipient.token, email, mailbox, name, role: recipient.role, fields };
  }

  return {
    envelopeId: envelope.id,
    documentId:
      type === EnvelopeType.TEMPLATE
        ? mapSecondaryIdToTemplateId(envelope.secondaryId)
        : mapSecondaryIdToDocumentId(envelope.secondaryId),
    internalVersion: options.internalVersion,
    title,
    owner,
    documentMetaId: documentMeta.id,
    itemId,
    r,
  };
};

