/**
 * 4.0 "Accepted, field routes" for a SIGNATURE field: 200, inserted, one
 * Signature row holding the value in the right column and null in the other,
 * one insert (or prefill) audit row whose data equals the stored value.
 */
export const expectSignatureAccepted = async (
  reply: Reply,
  seeded: G4Seeded,
  field: SeededField,
  kind: { image: { width: number; height: number; fixture?: string } } | { typed: string },
  what: string,
  auditType = 'DOCUMENT_FIELD_INSERTED',
) => {
  expect2xx(reply, what);

  const state = await fieldState(field.id);

  expect(state.inserted, `${what}: the field is inserted`).toBe(true);
  expect(state.signatureCount, `${what}: exactly one Signature row`).toBe(1);

  if ('typed' in kind) {
    expect(state.signature?.typed, `${what}: typedSignature is the trimmed text`).toBe(kind.typed);
    expect(state.signature?.image ?? null, `${what}: no image stored`).toBeNull();
  } else {
    expect(state.signature?.typed ?? null, `${what}: no typed signature stored`).toBeNull();
    expect(normalisedPngProblems(state.signature?.image, kind.image), `${what}: stored as the normalised PNG`).toEqual(
      [],
    );
  }

  const rows = await fieldAuditRowsOf(seeded.envelopeId, field.secondaryId, [auditType]);
  const stored = 'typed' in kind ? state.signature?.typed : state.signature?.image;

  expect(rows.length, `${what}: exactly one ${auditType} row`).toBe(1);
  expect(auditValueOf(rows[0]), `${what}: the audit row records the stored value`).toBe(stored);

  return state;
};

