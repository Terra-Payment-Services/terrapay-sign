/** Y composited over white; ink when Y < 230 (spec D1). */
export const isInkPixel = (r: number, g: number, b: number, alpha255: number) => {
  const a = alpha255 / 255;
  const y = a * (0.299 * r + 0.587 * g + 0.114 * b) + (1 - a) * 255;

  return y < 230;
};

export const coverageOf = (png: PNG) => {
  let ink = 0;

  for (let i = 0; i < png.data.length; i += 4) {
    if (isInkPixel(png.data[i], png.data[i + 1], png.data[i + 2], png.data[i + 3])) {
      ink++;
    }
  }

  return ink / (png.width * png.height);
};

export const decodePng = (bytes: Buffer) => PNG.sync.read(bytes);

/** Bounding box of pixels with alpha > 0. */
export const opaqueBoundingBox = (png: PNG) => {
  let minX = png.width;
  let minY = png.height;
  let maxX = -1;
  let maxY = -1;

  for (let y = 0; y < png.height; y++) {
    for (let x = 0; x < png.width; x++) {
      if (png.data[(y * png.width + x) * 4 + 3] > 0) {
        minX = Math.min(minX, x);
        minY = Math.min(minY, y);
        maxX = Math.max(maxX, x);
        maxY = Math.max(maxY, y);
      }
    }
  }

  return maxX < 0 ? null : { minX, minY, maxX, maxY, width: maxX - minX + 1, height: maxY - minY + 1 };
};

// ---------------------------------------------------------------------------
// PNG structure, for "stored as the normalised PNG" (section 3, rule 3)
// ---------------------------------------------------------------------------

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

export type PngChunk = { type: string; length: number; offset: number };

/** Walks the chunk list; `trailing` is the number of bytes after IEND. */
export const pngChunks = (bytes: Buffer) => {
  if (bytes.length < 8 || !bytes.subarray(0, 8).equals(PNG_SIGNATURE)) {
    return { isPng: false, chunks: [] as PngChunk[], trailing: 0, bitDepth: -1, colorType: -1 };
  }

  const chunks: PngChunk[] = [];
  let offset = 8;
  let bitDepth = -1;
  let colorType = -1;

  while (offset + 8 <= bytes.length) {
    const length = bytes.readUInt32BE(offset);
    const type = bytes.subarray(offset + 4, offset + 8).toString('latin1');

    if (type === 'IHDR') {
      bitDepth = bytes[offset + 16];
      colorType = bytes[offset + 17];
    }

    chunks.push({ type, length, offset });
    offset += 12 + length;

    if (type === 'IEND') {
      break;
    }
  }

  return { isPng: true, chunks, trailing: Math.max(bytes.length - offset, 0), bitDepth, colorType };
};

const CANONICAL_BASE64 = /^[A-Za-z0-9+/]+={0,2}$/;

/** One channel composited over white, 0..255. */
const overWhite = (channel: number, alpha255: number) => (alpha255 / 255) * channel + (1 - alpha255 / 255) * 255;

/**
 * Compares two decoded PNGs pixel by pixel, each composited over white, with a
 * tolerance of 1 per channel (16-bit sources rescale to 8 bits with either
 * rounding). Returns null when they match, or a description of the first
 * difference. For lossless fixtures: "the bytes every consumer sees are the
 * bytes that were validated" (section 3, rule 3) means the pixels survive.
 */
export const pixelMismatch = (stored: PNG, source: PNG) => {
  if (stored.width !== source.width || stored.height !== source.height) {
    return `size ${stored.width}x${stored.height} against ${source.width}x${source.height}`;
  }

  let differing = 0;
  let first = '';

  for (let i = 0; i < source.data.length; i += 4) {
    for (let c = 0; c < 3; c++) {
      const a = overWhite(stored.data[i + c], stored.data[i + 3]);
      const b = overWhite(source.data[i + c], source.data[i + 3]);

      if (Math.abs(a - b) > 1) {
        differing++;
        first ||= `pixel ${i / 4} channel ${c}: ${a.toFixed(1)} against ${b.toFixed(1)}`;
        break;
      }
    }
  }

  return differing === 0 ? null : `${differing} pixels differ; first ${first}`;
};

/**
 * Problems with a stored image value against section 3: exact prefix, canonical
 * base64, PNG signature, 8-bit RGBA, no tEXt/zTXt/iTXt, nothing after IEND,
 * pngjs decodes it, the source's dimensions, and D1 coverage above 1%.
 * Never asserts exact bytes: the encoder is the implementer's choice.
 */
export const normalisedPngProblems = (
  stored: string | null | undefined,
  source?: { width: number; height: number; fixture?: string },
) => {
  const problems: string[] = [];

  if (!stored) {
    return ['no stored image'];
  }

  if (!stored.startsWith(P)) {
    return [`stored value does not start with ${P}: ${JSON.stringify(stored.slice(0, 40))}`];
  }

  const payload = stored.slice(P.length);

  if (!CANONICAL_BASE64.test(payload) || payload.length % 4 !== 0) {
    problems.push('payload is not canonical padded base64');
  }

  const bytes = Buffer.from(payload, 'base64');

  if (bytes.toString('base64') !== payload) {
    problems.push('payload does not re-encode to itself');
  }

  const structure = pngChunks(bytes);

  if (!structure.isPng) {
    return [...problems, 'bytes do not start with the PNG signature'];
  }

  if (structure.bitDepth !== 8 || structure.colorType !== 6) {
    problems.push(`not 8-bit RGBA (bit depth ${structure.bitDepth}, colour type ${structure.colorType})`);
  }

  const textChunks = structure.chunks.filter((chunk) => ['tEXt', 'zTXt', 'iTXt'].includes(chunk.type));

  if (textChunks.length > 0) {
    problems.push(`carries ${textChunks.map((chunk) => chunk.type).join(', ')}`);
  }

  if (structure.trailing > 0) {
    problems.push(`${structure.trailing} bytes after IEND`);
  }

  try {
    const png = decodePng(bytes);

    if (source && (png.width !== source.width || png.height !== source.height)) {
      problems.push(`dimensions ${png.width}x${png.height}, source ${source.width}x${source.height}`);
    }

    if (coverageOf(png) <= 0.01) {
      problems.push(`D1 coverage ${coverageOf(png)} is not above 1%`);
    }

    if (source?.fixture) {
      const mismatch = pixelMismatch(png, decodePng(imageBytes(source.fixture)));

      if (mismatch) {
        problems.push(`pixels differ from fixture ${source.fixture}: ${mismatch}`);
      }
    }
  } catch (error) {
    problems.push(`pngjs cannot decode it: ${String(error).slice(0, 80)}`);
  }

  return problems;
};

