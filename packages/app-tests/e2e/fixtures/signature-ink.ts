const SESSION_LIFETIME_MS = 24 * 60 * 60 * 1000;

const hmacBase64 = async (value: string, secret: string) => {
  const key = await crypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(secret),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign'],
  );
  const signature = await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(value));

  return Buffer.from(signature).toString('base64');
};

/**
 * A session for `userId`, as sign-in would leave it: a Session row keyed by the
 * SHA-256 of a random token, and the token signed into the `sessionId` cookie.
 * Returns the cookie value, URL-encoded as the server sets it.
 */
export const seedSessionCookie = async (userId: number) => {
  const secret = process.env.NEXTAUTH_SECRET;

  if (!secret) {
    throw new Error('NEXTAUTH_SECRET is not in the test environment; the Playwright config loads it from .env');
  }

  const token = Buffer.from(crypto.getRandomValues(new Uint8Array(20))).toString('hex');
  const hashed = Buffer.from(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(token))).toString('hex');

  await prisma.session.create({
    data: {
      id: hashed,
      sessionToken: hashed,
      userId,
      expiresAt: new Date(Date.now() + SESSION_LIFETIME_MS),
    },
  });

  return encodeURIComponent(`${token}.${await hmacBase64(token, secret)}`);
};

export const SESSION_COOKIE = 'sessionId';

/** Signs the browser context (pages and `context.request`) in as `userId`. */
export const seedSession = async (context: BrowserContext, userId: number) => {
  const value = await seedSessionCookie(userId);
  const url = new URL(WEBAPP_BASE_URL);

  await context.addCookies([
    { name: SESSION_COOKIE, value, domain: url.hostname, path: '/', httpOnly: true, sameSite: 'Lax', secure: false },
  ]);

  return context.request;
};

/** Headers for a session tRPC call from a bare APIRequestContext. */
export const sessionHeaders = async (userId: number, teamId?: number) => ({
  cookie: `${SESSION_COOKIE}=${await seedSessionCookie(userId)}`,
  ...(teamId !== undefined ? { 'x-team-id': String(teamId) } : {}),
});

