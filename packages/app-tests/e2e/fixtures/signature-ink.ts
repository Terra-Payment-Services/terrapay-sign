/** Everything an out-of-turn request must leave alone. */
export const envelopeSnapshot = async (seeded: G4Seeded) => {
  const recipients = await prisma.recipient.findMany({
    where: { envelopeId: seeded.envelopeId },
    orderBy: { id: 'asc' },
    select: {
      id: true,
      signingStatus: true,
      readStatus: true,
      sendStatus: true,
      signedAt: true,
      rejectionReason: true,
      signingOrder: true,
      name: true,
      email: true,
    },
  });
  const fields = await prisma.field.findMany({
    where: { envelopeId: seeded.envelopeId },
    orderBy: { id: 'asc' },
    select: { id: true, inserted: true, customText: true, signature: true },
  });
  const envelope = await prisma.envelope.findUniqueOrThrow({
    where: { id: seeded.envelopeId },
    select: { status: true },
  });
  const auditCount = await prisma.documentAuditLog.count({ where: { envelopeId: seeded.envelopeId } });

  return { envelope, recipients, fields, auditCount };
};

export const mailboxCounts = async (request: APIRequestContext, seeded: G4Seeded) => {
  const counts: Record<string, number> = {};

  for (const [key, recipient] of Object.entries(seeded.r)) {
    counts[key] = (await readInbox(request, recipient.mailbox)).length;
  }

  // The owner is told of completions, rejections and cancellations; an out-of-turn request must send none.
  counts.owner = (await readInbox(request, seeded.owner.user.email.split('@')[0])).length;

  return counts;
};

/** How long an out-of-turn test waits for a late email before counting the mailboxes again (as G1's QUIET_WINDOW_MS). */
export const QUIET_MS = 6_000;

/**
 * Sends `call` and asserts the full out-of-turn refusal: 400
 * RECIPIENT_OUT_OF_TURN, nothing in the envelope changed, no audit row of any
 * type, no email to any recipient of the envelope.
 */
export const expectOutOfTurn = async (
  request: APIRequestContext,
  seeded: G4Seeded,
  call: () => Promise<Reply>,
  what: string,
  options: { checkMail?: boolean } = {},
) => {
  const checkMail = options.checkMail ?? true;
  const before = await envelopeSnapshot(seeded);
  const mailBefore = checkMail ? await mailboxCounts(request, seeded) : {};
  const reply = await call();

  expectRefusedWith(reply, 400, 'RECIPIENT_OUT_OF_TURN', what);

  if (checkMail) {
    await new Promise((resolve) => setTimeout(resolve, QUIET_MS));
  }

  const after = await envelopeSnapshot(seeded);

  expect(after.recipients, `${what}: no recipient column changed`).toEqual(before.recipients);
  expect(after.fields, `${what}: no field or Signature row changed`).toEqual(before.fields);
  expect(after.envelope, `${what}: envelope status unchanged`).toEqual(before.envelope);
  expect(after.auditCount, `${what}: no audit row of any type`).toBe(before.auditCount);

  if (checkMail) {
    expect(await mailboxCounts(request, seeded), `${what}: no email for the request`).toEqual(mailBefore);
  }

  return reply;
};

