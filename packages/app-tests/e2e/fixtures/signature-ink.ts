export type TrpcError = { status: number; code: string | undefined; httpStatus: number | undefined; message: string };

/** The status and the AppError code (`data.code`) of a reply (spec 4.0). */
export const errorOf = (reply: Reply): TrpcError => {
  let code: string | undefined;
  let httpStatus: number | undefined;
  let message = '';

  try {
    const body = JSON.parse(reply.body) as Record<string, unknown>;
    const error = ((body.error as Record<string, unknown> | undefined)?.json ?? body) as Record<string, unknown>;
    const data = (error.data ?? {}) as Record<string, unknown>;

    code = typeof data.code === 'string' ? data.code : typeof error.code === 'string' ? error.code : undefined;
    httpStatus = typeof data.httpStatus === 'number' ? data.httpStatus : undefined;
    message = String(error.message ?? '');
  } catch {
    message = reply.body.slice(0, 200);
  }

  return { status: reply.status, code, httpStatus, message };
};

export const describeReply = (reply: Reply) => `${reply.status} ${reply.body.slice(0, 300)}`;

export const expect2xx = (reply: Reply, what: string) => {
  expect(reply.status, `${what}: ${describeReply(reply)}`).toBeGreaterThanOrEqual(200);
  expect(reply.status, `${what}: ${describeReply(reply)}`).toBeLessThan(300);
};

/** Status and `data.code` exactly; a 429 is reported as a test defect. */
export const expectRefusedWith = (reply: Reply, status: number, code: string, what: string) => {
  expect(reply.status, `${what}: a 429 from the rate limiter is a test defect, not a result`).not.toBe(429);
  expect(reply.status, `${what}: expected ${status} ${code}, got ${describeReply(reply)}`).toBe(status);
  expect(errorOf(reply).code, `${what}: expected data.code ${code}, got ${describeReply(reply)}`).toBe(code);
};

